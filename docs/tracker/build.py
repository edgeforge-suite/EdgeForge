#!/usr/bin/env python3
"""Suite task tracker build: validate suite-tracker.json, regenerate the
Markdown mirror (README.md), and sync the embedded data block in index.html.

Stdlib only. Usage (from the repo root or docs/tracker/):

    python3 docs/tracker/build.py

The JSON data file is the single edit point; this script keeps the two rendered
views (README.md mirror + the embedded data in index.html) in lockstep so the
page also works when opened via file:// (where fetch() is blocked).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

TRACKER_DIR = Path(__file__).resolve().parent
DATA_FILE = TRACKER_DIR / "suite-tracker.json"
README_FILE = TRACKER_DIR / "README.md"
HTML_FILE = TRACKER_DIR / "index.html"

EMBED_START = "<!-- TRACKER-DATA:START (generated by build.py — do not edit by hand) -->"
EMBED_END = "<!-- TRACKER-DATA:END -->"

REQUIRED_FIELDS = [
    "id", "title", "summary", "priority", "complexity", "prs_estimate",
    "status", "category", "repo_impact", "wave", "source_doc",
    "depends_on", "last_updated",
]

PRIORITY_ORDER = ["now", "next", "later", "strategic", "adopter-gate", "future", "parked"]

# The roadmap execution guardrail M1 -> M5a -> M2/M6 -> M3 -> M4 -> M5b is 6 steps long today.
# Bump this only alongside a deliberate change to that guardrail in enterprise-readiness-roadmap.md.
SEQUENCE_RANK_MAX = 6

PRIORITY_LABELS = {
    "now": "Now — active / next up",
    "next": "Next — near-term queue",
    "later": "Later — sequenced behind current waves",
    "strategic": "Strategic — design-first / large tracks",
    "adopter-gate": "Adopter gates & post-import (adopter-owned)",
    "future": "Future",
    "parked": "Parked",
}


def fail(msg: str) -> None:
    print(f"VALIDATION ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def validate(data: dict) -> list[dict]:
    if "meta" not in data or "tasks" not in data:
        fail("top-level 'meta' and 'tasks' keys are required")
    vocab = data["meta"].get("vocabularies", {})
    tasks = data["tasks"]
    ids = set()
    for t in tasks:
        for f in REQUIRED_FIELDS:
            if f not in t:
                fail(f"task {t.get('id', '?')!r} missing required field {f!r}")
        if t["id"] in ids:
            fail(f"duplicate task id {t['id']!r}")
        ids.add(t["id"])
        for field in ("status", "priority", "category", "repo_impact"):
            allowed = vocab.get(field if field != "repo_impact" else "repo_impact")
            if allowed and t[field] not in allowed:
                fail(f"task {t['id']!r}: {field}={t[field]!r} not in vocabulary {allowed}")
        # design_status is an OPTIONAL facet describing the maturity of the DESIGN
        # artifact only (approved / in-review / exploratory). It is genuinely
        # orthogonal to build status: any status may carry any design maturity, and
        # a design stays 'approved' after the build ships. "Designed but not built"
        # is therefore a COMPOUND query (design_status=approved AND status in
        # {pending, blocked}), not a status value -- see HOWTO-update.md.
        if "design_status" in t:
            allowed = vocab.get("design_status")
            if allowed and t["design_status"] not in allowed:
                fail(f"task {t['id']!r}: design_status={t['design_status']!r} not in vocabulary {allowed}")
            if not t.get("design_ref"):
                fail(f"task {t['id']!r}: design_status requires design_ref (the design doc/PR it traces to)")
        # sequence_rank encodes the roadmap execution guardrail M1 -> M5a -> M2/M6 -> M3 -> M4 -> M5b
        # (enterprise-readiness-roadmap.md). Values outside that known 6-step order are almost
        # certainly a typo, not a deliberate 7th step -- extending the guardrail is a code change
        # to SEQUENCE_RANK_MAX below, not a value a task row should invent on its own.
        if "sequence_rank" in t:
            rank = t["sequence_rank"]
            if not isinstance(rank, int) or isinstance(rank, bool) or not (1 <= rank <= SEQUENCE_RANK_MAX):
                fail(
                    f"task {t['id']!r}: sequence_rank={rank!r} must be an integer 1..{SEQUENCE_RANK_MAX} "
                    "matching the roadmap execution guardrail (see HOWTO-update.md)"
                )
        if not isinstance(t["depends_on"], list):
            fail(f"task {t['id']!r}: depends_on must be a list")
    for t in tasks:
        for dep in t["depends_on"]:
            if dep not in ids:
                fail(f"task {t['id']!r} depends_on unknown id {dep!r}")
    raw = DATA_FILE.read_text(encoding="utf-8")
    local_user_home = "/" + "Users/"
    if local_user_home in raw or re.search(r"(/home/|[A-Za-z]:\\\\)", raw):
        fail("absolute local filesystem path found in data file")
    return tasks


# Repo prefixes marking sources that live OUTSIDE this repo (kept textual).
CROSS_REPO_PREFIXES = ("Studio:", "KS:", "TestBench:", "shared-specs:")
LOCAL_DOC_RE = re.compile(r"(docs/[A-Za-z0-9 _().\-/]+\.md|CHANGELOG\.md)")
REPO_ROOT = TRACKER_DIR.parent.parent


def _href_for(path: str) -> str:
    """Relative href from docs/tracker/ to a repo-root-relative doc path."""
    rel = "../" + path[len("docs/"):] if path.startswith("docs/") else "../../" + path
    return rel.replace(" ", "%20")


def linkify_source(source: str, html: bool = False) -> str:
    """Turn Engine-local doc paths in a source citation into links, verifying
    each target exists (broken links are a build failure). Chunks naming a
    cross-repo source (Studio:/KS:/...) stay textual."""
    out = []
    for chunk in re.split(r"( \+ |; )", source):
        if chunk in (" + ", "; ") or any(p in chunk for p in CROSS_REPO_PREFIXES):
            out.append(chunk)
            continue

        def repl(m: re.Match) -> str:
            path = m.group(1)
            if not (REPO_ROOT / path).exists():
                fail(f"source citation points to a missing file: {path!r}")
            href = _href_for(path)
            if html:
                return f'<a href="{href}">{path}</a>'
            return f"[{path}]({href})"

        out.append(LOCAL_DOC_RE.sub(repl, chunk))
    return "".join(out)


def md_escape(s: str) -> str:
    return s.replace("|", "\\|")


def render_readme(data: dict) -> str:
    meta = data["meta"]
    tasks = data["tasks"]
    counts: dict[str, int] = {}
    for t in tasks:
        counts[t["status"]] = counts.get(t["status"], 0) + 1
    count_line = " · ".join(
        f"**{counts[s]}** {s}" for s in
        ["pending", "in-progress", "blocked", "adopter-decides", "parked", "done"]
        if s in counts
    )
    design_counts: dict[str, int] = {}
    for t in tasks:
        if t.get("design_status"):
            design_counts[t["design_status"]] = design_counts.get(t["design_status"], 0) + 1
    design_line = " · ".join(
        f"**{design_counts[d]}** {d}" for d in
        ["approved", "in-review", "exploratory"]
        if d in design_counts
    )
    build_pending = sum(
        1 for t in tasks
        if t.get("design_status") == "approved" and t["status"] in ("pending", "blocked")
    )
    lines = [
        "# EdgeForge Suite Task Tracker (derived view)",
        "",
        "> **Generated file — do not edit.** Edit [`suite-tracker.json`](suite-tracker.json)",
        "> and run `python3 docs/tracker/build.py` (see [`HOWTO-update.md`](HOWTO-update.md)).",
        "> The roadmaps remain the narrative source of truth; this tracker is a derived view.",
        ">",
        f"> **Snapshot:** {meta['snapshot_date']} · **{len(tasks)} tasks** · {count_line}",
        ">",
    ] + ([
        f"> **Design maturity** (orthogonal facet — describes the design artifact, not the build; "
        f"**a bounded, hand-audited record, not exhaustive across all {len(tasks)} tasks** — a row with "
        "no facet has simply not been checked yet, it is not thereby unapproved): "
        f"{design_line}. **{build_pending}** are `approved` **and** still `pending`/`blocked` — i.e. "
        "*designed, build not started* (a compound query, not a status).",
        ">",
    ] if design_line else []) + [
        "> Interactive view: open [`index.html`](index.html) locally or via GitHub Pages.",
        "",
        "Snapshot points: " + "; ".join(f"{k}: `{v}`" for k, v in meta["snapshots"].items()),
        "",
    ]
    for tier in PRIORITY_ORDER:
        tier_tasks = [t for t in tasks if t["priority"] == tier]
        if not tier_tasks:
            continue
        # Preserve the roadmap execution guardrail (M1 -> M5a -> M2/M6 -> M3 -> M4 -> M5b)
        # inside a tier; unranked rows keep file order after ranked ones.
        tier_tasks.sort(key=lambda t: (t.get("sequence_rank", 999), tasks.index(t)))
        lines.append(f"## {PRIORITY_LABELS.get(tier, tier)} ({len(tier_tasks)})")
        lines.append("")
        lines.append("| ID | Title | Status | Category | Repo | Cx | ~PRs | Wave | Depends on | Source |")
        lines.append("|---|---|---|---|---|---|---|---|---|---|")
        for t in tier_tasks:
            deps = ", ".join(t["depends_on"]) if t["depends_on"] else "—"
            if t.get("blocked_by"):
                deps = (deps + "; " if deps != "—" else "") + f"blocked by: {t['blocked_by']}"
            lines.append(
                "| `{id}` | **{title}**<br>{summary} | {status} | {category} | {repo} | {cx} | {prs} | {wave} | {deps} | {src} |".format(
                    id=t["id"],
                    title=md_escape(t["title"]),
                    summary=md_escape(t["summary"]),
                    status=t["status"],
                    category=t["category"],
                    repo=t["repo_impact"],
                    cx=t["complexity"],
                    prs=t["prs_estimate"],
                    wave=md_escape(t["wave"]),
                    deps=md_escape(deps),
                    src=linkify_source(md_escape(t["source_doc"])),
                )
            )
        lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("*" + meta["description"] + "*")
    lines.append("")
    return "\n".join(lines)


def inject_html(data: dict) -> None:
    if not HTML_FILE.exists():
        print("index.html not found — skipping embed sync")
        return
    html = HTML_FILE.read_text(encoding="utf-8")
    start = html.find(EMBED_START)
    end = html.find(EMBED_END)
    if start == -1 or end == -1:
        fail("index.html is missing the TRACKER-DATA embed markers")
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    block = (
        f"{EMBED_START}\n"
        f'<script id="tracker-data" type="application/json">{payload}</script>\n'
    )
    new_html = html[:start] + block + html[end:]
    HTML_FILE.write_text(new_html, encoding="utf-8")


def main() -> None:
    data = json.loads(DATA_FILE.read_text(encoding="utf-8"))
    tasks = validate(data)
    README_FILE.write_text(render_readme(data), encoding="utf-8")
    inject_html(data)
    print(f"OK: {len(tasks)} tasks validated; README.md regenerated; index.html embed synced.")


if __name__ == "__main__":
    main()
