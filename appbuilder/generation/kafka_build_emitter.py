"""Emit build files for the kafka-integration archetype."""

from __future__ import annotations

import copy
import json
import re
from typing import Any

from appbuilder.generation.audit import render_generated_file_header
from appbuilder.generation.build_emitter import _deployment_security_note_lines
from appbuilder.generation.container_policy import base_references
from appbuilder.generation.dependency_policy import kafka_dependency_management, policy_properties
from appbuilder.generation.kafka_compatibility import is_boot41
from appbuilder.generation.plugin_policy import build_plugins
from appbuilder.metadata.kafka_models import KafkaMetadata


def emit(
    metadata: KafkaMetadata,
    *,
    source_manifest: str = "metadata-project",
    generation_run_id: str = "kafka",
) -> dict[str, str]:
    """Return build/configuration files for a generated Kafka integration app."""

    files = {
        "pom.xml": _render_pom_xml(
            metadata,
            source_manifest=source_manifest,
            generation_run_id=generation_run_id,
        ),
        "src/main/resources/application.yaml": _render_application_yaml(
            metadata,
            source_manifest=source_manifest,
            generation_run_id=generation_run_id,
        ),
        "Dockerfile": _render_dockerfile(
            metadata,
            source_manifest=source_manifest,
            generation_run_id=generation_run_id,
        ),
        "README.md": _render_readme(
            metadata,
            source_manifest=source_manifest,
            generation_run_id=generation_run_id,
        ),
    }
    files.update(_router_schema_resource_files(metadata))
    return files


def _render_pom_xml(
    metadata: KafkaMetadata,
    *,
    source_manifest: str,
    generation_run_id: str,
) -> str:
    header = _header(
        metadata,
        comment_style="xml",
        source_manifest=source_manifest,
        generation_run_id=generation_run_id,
    )
    preview = is_boot41(metadata.target_profile_name)
    dependencies = [
        _dependency("org.springframework.boot", "spring-boot-starter-webmvc" if preview else "spring-boot-starter-web"),
        _dependency("org.springframework.boot", "spring-boot-starter-kafka") if preview else _dependency("org.springframework.kafka", "spring-kafka"),
        _dependency("org.springframework.boot", "spring-boot-starter-actuator"),
        _dependency("io.micrometer", "micrometer-registry-prometheus"),
        _dependency("org.springframework.boot", "spring-boot-starter-test", scope="test"),
        _dependency("org.springframework.kafka", "spring-kafka-test", scope="test"),
    ]
    if metadata.router_routes:
        dependencies.insert(
            4,
            _dependency("com.networknt", "json-schema-validator", version="3.0.6" if preview else "1.0.87"),
        )
    if preview:
        dependencies.insert(2, _dependency("org.springframework.boot", "spring-boot-starter-jackson"))
    return "\n".join(
        [
            header,
            "<project xmlns=\"http://maven.apache.org/POM/4.0.0\"",
            "         xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\"",
            "         xsi:schemaLocation=\"http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd\">",
            "    <modelVersion>4.0.0</modelVersion>",
            "    <parent>",
            "        <groupId>org.springframework.boot</groupId>",
            "        <artifactId>spring-boot-starter-parent</artifactId>",
            f"        <version>{metadata.spring_boot_version}</version>",
            "        <relativePath/>",
            "    </parent>",
            "    <groupId>com.appbuilder</groupId>",
            f"    <artifactId>{metadata.artifact_id}</artifactId>",
            "    <version>0.0.1-SNAPSHOT</version>",
            f"    <name>{metadata.app_name}</name>",
            f"    <description>{metadata.app_name} kafka-integration generated by EdgeForge</description>",
            "    <properties>",
            f"        <java.version>{metadata.java_version}</java.version>",
            *policy_properties(preview),
            "    </properties>",
            *kafka_dependency_management(preview),
            "    <dependencies>",
            *dependencies,
            "    </dependencies>",
            "    <build>",
            "        <plugins>",
            *build_plugins(preview),
            "        </plugins>",
            "    </build>",
            "</project>",
            "",
        ]
    )


def _render_application_yaml(
    metadata: KafkaMetadata,
    *,
    source_manifest: str,
    generation_run_id: str,
) -> str:
    lines = [
        _header(
            metadata,
            comment_style="hash",
            source_manifest=source_manifest,
            generation_run_id=generation_run_id,
        ),
        "server:",
        "  port: 8080",
        "  shutdown: graceful",
        "",
        "spring:",
        "  lifecycle:",
        "    timeout-per-shutdown-phase: 30s",
        "  kafka:",
        "    bootstrap-servers: ${KAFKA_BOOTSTRAP_SERVERS:localhost:9092}",
        "    consumer:",
        f"      group-id: {metadata.consumer_group}",
        "      auto-offset-reset: earliest",
        "      enable-auto-commit: false",
        "    listener:",
        "      observation-enabled: true",
        "    producer:",
        "      acks: all",
        "",
        "app:",
        "  kafka:",
    ]
    if metadata.routes:
        lines.append("    topics:")
        for route in metadata.routes:
            env_prefix = _upper_snake(route.name)
            route_lines = [
                f"      {route.name}:",
                f"        inbound: ${{TOPIC_{env_prefix}_INBOUND:{route.upstream_topic_name}}}",
                f"        outbound: ${{TOPIC_{env_prefix}_OUTBOUND:{route.downstream_topic_name}}}",
            ]
            if metadata.dlq_policy is not None:
                if route.pattern == "request-reply":
                    route_lines.extend(
                        [
                            f"        dlq-inbound: ${{TOPIC_{env_prefix}_DLQ_INBOUND:{route.upstream_topic_name}{metadata.dlq_policy.topic_suffix}}}",
                            f"        dlq-reply: ${{TOPIC_{env_prefix}_DLQ_REPLY:{route.downstream_reply_topic_name}{metadata.dlq_policy.topic_suffix}}}",
                        ]
                    )
                else:
                    route_lines.append(
                        f"        dlq: ${{TOPIC_{env_prefix}_DLQ:{route.upstream_topic_name}{metadata.dlq_policy.topic_suffix}}}"
                    )
            if route.pattern == "request-reply":
                route_lines.extend(
                    [
                        f"        downstream-reply: ${{TOPIC_{env_prefix}_DOWNSTREAM_REPLY:{route.downstream_reply_topic_name}}}",
                        f"        upstream-reply: ${{TOPIC_{env_prefix}_UPSTREAM_REPLY:{route.upstream_reply_topic_name}}}",
                        f"        timeout-ms: ${{TIMEOUT_{env_prefix}_MS:{route.reply_timeout_ms}}}",
                    ]
                )
            lines.extend(route_lines)
    if metadata.router_routes:
        lines.extend(["    router:"])
        for route in metadata.router_routes:
            route_env_prefix = _upper_snake(route.name)
            lines.extend(
                [
                    f"      {route.name}:",
                    "        upstream:",
                ]
            )
            for topic in route.upstream_topics:
                topic_env_prefix = _upper_snake(f"{route.name}_{topic.id}")
                lines.extend(
                    [
                        f"          {topic.id}:",
                        f"            topic: ${{TOPIC_{topic_env_prefix}_UPSTREAM:{topic.name}}}",
                        f"            consumer-group: ${{CONSUMER_GROUP_{topic_env_prefix}:{topic.consumer_group}}}",
                    ]
                )
            lines.extend(["        targets:"])
            for target in route.targets:
                target_env_prefix = _upper_snake(f"{route.name}_{target.id}")
                lines.extend(
                    [
                        f"          {target.id}:",
                        f"            request-topic: ${{TOPIC_{target_env_prefix}_REQUEST:{target.request_topic}}}",
                        f"            response-topic: ${{TOPIC_{target_env_prefix}_RESPONSE:{target.response_topic}}}",
                        f"            timeout-ms: ${{TIMEOUT_{target_env_prefix}_MS:{target.timeout_ms}}}",
                    ]
                )
            lines.extend(
                [
                    "        nack:",
                    f"          mode: {route.nack_routing.mode}",
                    f"          fixed-topic: ${{TOPIC_{route_env_prefix}_NACK:{route.nack_routing.fixed_topic or route.nack_routing.default_error_topic}}}",
                    f"          default-error-topic: ${{TOPIC_{route_env_prefix}_ERROR:{route.nack_routing.default_error_topic}}}",
                    "        reply-destination:",
                    f"          allowed-topics: ${{ROUTER_{route_env_prefix}_REPLY_ALLOWED_TOPICS:}}",
                    f"          allowed-prefixes: ${{ROUTER_{route_env_prefix}_REPLY_ALLOWED_PREFIXES:}}",
                    f"        duplicate-correlation-policy: ${{ROUTER_{route_env_prefix}_DUPLICATE_CORRELATION_POLICY:{route.duplicate_correlation_policy}}}",
                    "        timeout:",
                    f"          behavior-with-known-reply: {route.timeout.behavior_with_known_reply}",
                    f"          behavior-without-reply: {route.timeout.behavior_without_reply}",
                    f"          correlation-store-ms: ${{TIMEOUT_{route_env_prefix}_CORRELATION_MS:{route.correlation_store.timeout_ms}}}",
                    f"          eviction-interval-ms: ${{TIMEOUT_{route_env_prefix}_EVICTION_MS:{route.correlation_store.eviction_interval_ms}}}",
                    "        payload-logging:",
                    f"          policy: {route.payload_logging.policy}",
                    f"          capped-raw-bytes: {route.payload_logging.capped_raw_bytes}",
                ]
            )
    lines.extend(
        [
            "",
            "management:",
            "  endpoints:",
            "    web:",
            "      exposure:",
            "        include: ${MANAGEMENT_ENDPOINTS_WEB_EXPOSURE_INCLUDE:health}",
            "  endpoint:",
            "    health:",
            "      show-details: when-authorized",
            "      roles: ACTUATOR",
            "",
        ]
    )
    return "\n".join(lines)


def _render_dockerfile(
    metadata: KafkaMetadata,
    *,
    source_manifest: str,
    generation_run_id: str,
) -> str:
    build_base, runtime_base = base_references(metadata.java_version)
    header = _header(
        metadata,
        comment_style="hash",
        source_manifest=source_manifest,
        generation_run_id=generation_run_id,
    )
    return "\n".join(
        [
            header,
            f"FROM {build_base} AS build",
            "WORKDIR /workspace",
            "COPY pom.xml .",
            "COPY src src",
            "RUN mvn -q -DskipTests clean package",
            "",
            f"FROM {runtime_base}",
            "WORKDIR /app",
            "RUN groupadd --system edgeforge && useradd --system --gid edgeforge --home-dir /app --shell /usr/sbin/nologin edgeforge",
            f"COPY --from=build --chown=edgeforge:edgeforge /workspace/target/{metadata.artifact_id}-0.0.1-SNAPSHOT.jar app.jar",
            "RUN chown -R edgeforge:edgeforge /app",
            "EXPOSE 8080",
            "HEALTHCHECK --interval=30s --timeout=5s --retries=3 CMD wget --quiet --tries=1 --spider http://localhost:8080/actuator/health || exit 1",
            "USER edgeforge",
            "ENTRYPOINT [\"java\", \"-jar\", \"/app/app.jar\"]",
            "",
        ]
    )


def _render_readme(
    metadata: KafkaMetadata,
    *,
    source_manifest: str,
    generation_run_id: str,
) -> str:
    route_lines = []
    for route in metadata.routes:
        if route.pattern == "request-reply":
            route_lines.append(
                f"- `{route.name}`: `{route.upstream_topic_name}` -> "
                f"`{route.downstream_topic_name}` -> reply "
                f"`{route.downstream_reply_topic_name}` -> `{route.upstream_reply_topic_name}`"
            )
        else:
            route_lines.append(
                f"- `{route.name}`: `{route.upstream_topic_name}` -> `{route.downstream_topic_name}`"
            )
    for route in metadata.router_routes:
        upstream_topics = ", ".join(topic.name for topic in route.upstream_topics)
        target_topics = ", ".join(target.request_topic for target in route.targets)
        route_lines.append(
            f"- `{route.name}` router request path: `{upstream_topics}` -> `{target_topics}`"
        )
    return "\n".join(
        [
            _header(
                metadata,
                comment_style="xml",
                source_manifest=source_manifest,
                generation_run_id=generation_run_id,
            ),
            f"# {metadata.app_name}",
            "",
            f"Bounded context: `{metadata.bounded_context}`",
            f"Manifest schema version: `{metadata.schema_version}`",
            "",
            (
                "Generated by EdgeForge. Follow each file's `EdgeForge-ownership` "
                "marker before editing; this archetype does not emit the CRUD "
                "`Service`/`ServiceBase` extension seam."
            ),
            "",
            "## Archetype",
            "",
            "`kafka-integration` — Kafka topic-to-topic mediation with deterministic transforms.",
            "",
            "## Build",
            "",
            "```bash",
            "mvn clean package",
            "```",
            "",
            "## Run",
            "",
            "```bash",
            "java -jar target/*.jar",
            "```",
            "",
            *_deployment_security_note_lines(),
            "## Routes",
            "",
            *route_lines,
            "",
            "## Processing Semantics",
            "",
            "This application uses **at-least-once** Kafka processing semantics.",
            "Messages are acknowledged only after a successful transform and downstream",
            "publish. Duplicate delivery is possible if the application restarts after a",
            "successful publish but before acknowledgement. Consumers of downstream topics",
            "should implement idempotency where required.",
            "",
            "Exactly-once end-to-end semantics are not provided in this version.",
            "",
            *([
                "## Spring Boot 4.1 Fresh Applications",
                "",
                "Ordinary profiles use Boot 4.1.1 and dependency policy ef-v5-maven-1; Kafka",
                "remains datasource/Batch-free even on PostgreSQL-named profiles.",
                "Request/reply correlation is in-memory and is not durable across restart.",
                "Router validation retains draft-07/2020-12, strict types and format checks.",
                "Validator diagnostic wording and technical DLQ stack traces differ from",
                "Boot 3; NACK fields/codes/boundaries and original DLQ payloads are retained.",
                "This is fresh-app compatibility proof, not M2 or release clearance.",
                "Boot 3 or ambiguous retained packages refuse generate/plan/apply before writes.",
                "",
            ] if is_boot41(metadata.target_profile_name) else []),
            "## Retry Policy",
            "",
            *_retry_policy_lines(metadata),
            "",
            "## Observability",
            "",
            "Only `/actuator/health` is exposed by default.",
            (
                "To expose metrics and Prometheus, set "
                "`MANAGEMENT_ENDPOINTS_WEB_EXPOSURE_INCLUDE=health,metrics,prometheus`."
            ),
            (
                "Enable those endpoints only when the application port is unreachable "
                "except through the authenticated, TLS-terminating gateway."
            ),
            "Kafka listener metrics are exported under `spring.kafka.listener.*`.",
            "",
        ]
    )


def _router_schema_resource_files(metadata: KafkaMetadata) -> dict[str, str]:
    files: dict[str, str] = {}
    for route in metadata.router_routes:
        schema_refs = [
            route.inbound_schema,
            route.outbound_schema,
            *[target.request_schema for target in route.targets],
            *[target.response_schema for target in route.targets],
        ]
        for schema_ref in schema_refs:
            if schema_ref.content is None:
                continue
            content = _router_schema_resource_content(schema_ref.content, schema_ref.validation_policy)
            files[f"src/main/resources/{schema_ref.file}"] = (
                json.dumps(content, indent=2, sort_keys=True) + "\n"
            )
    return files


def _router_schema_resource_content(
    content: dict[str, Any],
    validation_policy: str,
) -> dict[str, Any]:
    schema = copy.deepcopy(content)
    if validation_policy == "strict":
        _apply_strict_additional_properties(schema)
    return schema


def _apply_strict_additional_properties(node: Any) -> None:
    if not isinstance(node, dict):
        return
    properties = node.get("properties")
    if node.get("type") == "object" or isinstance(properties, dict):
        node["additionalProperties"] = False
    if isinstance(properties, dict):
        for child_schema in properties.values():
            _apply_strict_additional_properties(child_schema)
    items = node.get("items")
    if isinstance(items, dict):
        _apply_strict_additional_properties(items)
    for composite_key in ("oneOf", "anyOf", "allOf"):
        variants = node.get(composite_key)
        if isinstance(variants, list):
            for variant in variants:
                _apply_strict_additional_properties(variant)


def _retry_policy_lines(metadata: KafkaMetadata) -> list[str]:
    if metadata.retry_policy is None:
        return [
            "No retry policy is configured. Failed messages are handled by Spring Kafka's",
            "default error handler (immediate redelivery up to Spring Kafka defaults).",
        ]

    backoff_kind = "exponential" if metadata.retry_policy.backoff_multiplier > 1.0 else "fixed"
    lines = [
        f"Processing failures are retried up to {metadata.retry_policy.max_attempts} times using",
        f"{backoff_kind} backoff starting at {metadata.retry_policy.backoff_ms}ms.",
    ]
    if backoff_kind == "exponential":
        lines.append(f"Backoff multiplier: {metadata.retry_policy.backoff_multiplier}x.")
    if metadata.dlq_policy is not None:
        lines.append(
            "After exhausting retries, messages are forwarded to the DLQ topic"
        )
        lines.append(
            f"(inbound topic name + \"{metadata.dlq_policy.topic_suffix}\")."
        )
    return lines


def _dependency(
    group_id: str,
    artifact_id: str,
    *,
    version: str | None = None,
    scope: str | None = None,
) -> str:
    lines = [
        "        <dependency>",
        f"            <groupId>{group_id}</groupId>",
        f"            <artifactId>{artifact_id}</artifactId>",
    ]
    if version is not None:
        lines.append(f"            <version>{version}</version>")
    if scope is not None:
        lines.append(f"            <scope>{scope}</scope>")
    lines.append("        </dependency>")
    return "\n".join(lines)


def _header(
    metadata: KafkaMetadata,
    *,
    comment_style: str,
    source_manifest: str,
    generation_run_id: str,
) -> str:
    return render_generated_file_header(
        source_manifest=source_manifest,
        target_profile=metadata.target_profile_name,
        generation_run_id=generation_run_id,
        comment_style=comment_style,
    )


def _upper_snake(value: str) -> str:
    normalized = re.sub(r"[^a-zA-Z0-9]+", "_", value).strip("_")
    return normalized.upper() or "TOPIC"
