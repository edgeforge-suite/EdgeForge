"""Regeneration-mode detection and ownership-aware cleanup helpers."""

from __future__ import annotations

import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

from appbuilder.metadata.models import MetadataProject

from .durable_json import load_durable_json
from .schema_baseline import SCHEMA_BASELINE_RELATIVE_PATH
from .utils import base_package, package_path

GenerationMode = Literal["greenfield", "regenerate", "legacy"]


@dataclass
class GenerationContext:
    """Detected regeneration state for a generation run."""

    mode: GenerationMode
    baseline: dict[str, Any] | None = None
    warnings: list[str] = field(default_factory=list)


def detect_generation_context(output_dir: Path) -> GenerationContext:
    """Classify an output directory before generation starts."""

    if not output_dir.exists() or not any(output_dir.iterdir()):
        return GenerationContext(mode="greenfield")

    baseline_path = output_dir / SCHEMA_BASELINE_RELATIVE_PATH
    baseline = None
    if baseline_path.exists():
        baseline = _load_baseline(baseline_path)

    ownership_headers = _find_files_with_marker(output_dir, "EdgeForge-ownership:")
    generated_headers = _find_files_with_marker(output_dir, "Generated by EdgeForge")

    if baseline_path.exists() and ownership_headers:
        return GenerationContext(mode="regenerate", baseline=baseline)
    if generated_headers:
        warning = (
            "legacy generated package detected; seeding regeneration baseline and "
            "upgrading ownership headers where generated files are refreshed."
        )
        return GenerationContext(mode="legacy", baseline=baseline, warnings=[warning])
    return GenerationContext(mode="greenfield", baseline=baseline)


def prune_orphaned_generated_sources(
    *,
    metadata: MetadataProject,
    output_dir: Path,
    previous_baseline: dict[str, Any] | None,
) -> list[str]:
    """Remove generated-owned Java sources for entities absent from the new manifest."""

    if not previous_baseline:
        return []

    current_entities = {entity.name for entity in metadata.entities if entity.fields}
    warnings: list[str] = []
    for entity_snapshot in previous_baseline.get("entities", []):
        entity_name = entity_snapshot.get("entity")
        if not entity_name or entity_name in current_entities:
            continue
        generated_sources = entity_snapshot.get("generated_source_files")
        if not generated_sources:
            generated_sources = _fallback_generated_sources_for_removed_entity(
                metadata=metadata,
                entity_name=entity_name,
            )
        for relative_path in sorted(set(generated_sources)):
            path = output_dir / relative_path
            if not path.exists() or not path.is_file():
                continue
            ownership = read_edgeforge_ownership(path)
            if ownership == "generated":
                path.unlink()
            elif ownership == "developer":
                backup_path = _archive_orphaned_developer_file(path)
                warnings.append(
                    _orphaned_developer_warning(entity_name, output_dir, path, backup_path)
                )
    for warning in _warn_orphaned_developer_services(
        metadata=metadata,
        output_dir=output_dir,
        removed_entities={
            snapshot.get("entity")
            for snapshot in previous_baseline.get("entities", [])
            if snapshot.get("entity") and snapshot.get("entity") not in current_entities
        },
    ):
        if warning not in warnings:
            warnings.append(warning)
    return warnings


def prune_stale_generated_java_sources(
    *,
    output_dir: Path,
    current_files: list[Path],
) -> list[str]:
    """Prune generated Java files that were not emitted by the current run."""

    java_root = output_dir / "src" / "main" / "java"
    if not java_root.exists():
        return []
    current_paths = {path.resolve() for path in current_files if path.suffix == ".java"}
    warnings: list[str] = []
    for path in sorted(java_root.rglob("*.java")):
        if path.resolve() in current_paths:
            continue
        if read_edgeforge_ownership(path) != "generated":
            continue
        relative_path = path.relative_to(output_dir).as_posix()
        path.unlink()
        warnings.append(f"generated stale Java source pruned: {relative_path}")
    return warnings


def prune_generated_artifacts(
    *,
    output_dir: Path,
    relative_paths: tuple[str, ...],
    artifact_label: str,
) -> list[str]:
    """Remove generated artifacts that the selected profile no longer emits.

    Pre-ownership generated files are archived first because they may contain
    legacy hand edits that EdgeForge cannot distinguish from generated content.
    """

    warnings: list[str] = []
    for relative_path in relative_paths:
        path = output_dir / relative_path
        if not path.is_file():
            continue
        ownership = read_edgeforge_ownership(path)
        legacy_generated = ownership is None and _file_has_marker(
            path, "Generated by EdgeForge"
        )
        if ownership != "generated" and not legacy_generated:
            continue
        if legacy_generated:
            content = path.read_text(encoding="utf-8")
            backup_path = _legacy_backup_path_for_output(
                output_dir=output_dir,
                path=path,
                content=content,
            )
            if not backup_path.exists():
                backup_path.write_text(content, encoding="utf-8")
        path.unlink()
        warnings.append(
            f"generated {artifact_label} artifact pruned: {relative_path}"
        )
    return warnings


def prune_stale_test_console_build_output(
    *,
    output_dir: Path,
    source_artifacts_pruned: bool,
) -> list[str]:
    """Remove disposable Maven output that can retain a previously emitted console."""

    target_dir = output_dir / "target"
    if not target_dir.is_dir():
        return []

    classes_dir = target_dir / "classes"
    stale_resource_paths = list(
        (classes_dir / "static").glob("index.html*")
    )
    stale_controller_paths = list(classes_dir.rglob("DemoController*.class"))
    if (
        not source_artifacts_pruned
        and not stale_resource_paths
        and not stale_controller_paths
    ):
        return []

    shutil.rmtree(target_dir)
    return ["generated stale test-console build output pruned: target"]


def protect_legacy_generated_files(output_dir: Path) -> list[str]:
    """Back up pre-ownership generated files before they are overwritten.

    Legacy packages only carried the "Generated by EdgeForge" marker. Without an
    ownership line we cannot safely know whether a generated file was hand-edited,
    so the adoption pass preserves the current bytes before refreshed generated
    output adds ownership headers.
    """

    warnings: list[str] = []
    for path in _find_files_with_marker(output_dir, "Generated by EdgeForge"):
        if ".legacy.bak" in path.name:
            continue
        if read_edgeforge_ownership(path) is not None:
            continue
        try:
            content = path.read_text(encoding="utf-8")
        except OSError:
            continue
        backup_path = _legacy_backup_path_for_output(
            output_dir=output_dir,
            path=path,
            content=content,
        )
        if not backup_path.exists():
            backup_path.write_text(content, encoding="utf-8")
        relative_path = path.relative_to(output_dir).as_posix()
        backup_label = (
            backup_path.name
            if backup_path.parent == path.parent
            else backup_path.relative_to(output_dir).as_posix()
        )
        warnings.append(
            f"legacy generated file preserved before ownership adoption: "
            f"{relative_path} -> {backup_label}"
        )
    return warnings


def read_edgeforge_ownership(path: Path) -> str | None:
    try:
        lines = path.read_text(encoding="utf-8", errors="ignore").splitlines()[:8]
    except OSError:
        return None
    for line in lines:
        if "EdgeForge-ownership:" not in line:
            continue
        return line.split("EdgeForge-ownership:", 1)[1].strip().split()[0]
    return None


def _find_files_with_marker(output_dir: Path, marker: str) -> list[Path]:
    matches: list[Path] = []
    for path in output_dir.rglob("*"):
        if not path.is_file():
            continue
        try:
            header = path.read_text(encoding="utf-8", errors="ignore").splitlines()[:8]
        except OSError:
            continue
        if any(marker in line for line in header):
            matches.append(path)
    return matches


def _file_has_marker(path: Path, marker: str) -> bool:
    try:
        header = path.read_text(encoding="utf-8", errors="ignore").splitlines()[:8]
    except OSError:
        return False
    return any(marker in line for line in header)


def _load_baseline(path: Path) -> dict[str, Any]:
    try:
        baseline = load_durable_json(path)
    except Exception as exc:
        raise ValueError(
            f"Invalid EdgeForge schema baseline at {path}: regenerate cannot proceed. "
            "Restore a valid db/schema-baseline.json or regenerate into a clean output directory."
        ) from exc
    if not isinstance(baseline, dict):
        raise ValueError(
            f"Invalid EdgeForge schema baseline at {path}: expected a JSON object."
        )
    if not isinstance(baseline.get("entities"), list):
        raise ValueError(
            f"Invalid EdgeForge schema baseline at {path}: missing entities list."
        )
    return baseline


def _legacy_backup_path(path: Path, content: str) -> Path:
    backup_path = path.with_name(f"{path.name}.legacy.bak")
    if not backup_path.exists() or backup_path.read_text(encoding="utf-8") == content:
        return backup_path

    index = 1
    while True:
        candidate = path.with_name(f"{path.name}.legacy.bak.{index}")
        if not candidate.exists() or candidate.read_text(encoding="utf-8") == content:
            return candidate
        index += 1


def _legacy_backup_path_for_output(
    *,
    output_dir: Path,
    path: Path,
    content: str,
) -> Path:
    """Keep resource backups outside Maven's packaged resource tree."""

    relative_path = path.relative_to(output_dir)
    if relative_path.parts[:3] == ("src", "main", "resources"):
        archive_path = output_dir / ".edgeforge-backups" / relative_path
        archive_path.parent.mkdir(parents=True, exist_ok=True)
        return _legacy_backup_path(archive_path, content)
    return _legacy_backup_path(path, content)


def _archive_orphaned_developer_file(path: Path) -> Path:
    content = path.read_text(encoding="utf-8")
    backup_path = _orphan_backup_path(path, content)
    if not backup_path.exists():
        backup_path.write_text(content, encoding="utf-8")
    path.unlink()
    return backup_path


def _orphan_backup_path(path: Path, content: str) -> Path:
    backup_path = path.with_name(f"{path.name}.orphaned.bak")
    if not backup_path.exists() or backup_path.read_text(encoding="utf-8") == content:
        return backup_path

    index = 1
    while True:
        candidate = path.with_name(f"{path.name}.orphaned.bak.{index}")
        if not candidate.exists() or candidate.read_text(encoding="utf-8") == content:
            return candidate
        index += 1


def _orphaned_developer_warning(
    entity_name: str,
    output_dir: Path,
    original_path: Path,
    backup_path: Path,
) -> str:
    relative_path = original_path.relative_to(output_dir).as_posix()
    return (
        f"{entity_name}: developer-owned orphan source preserved as {backup_path.name} "
        f"from {relative_path}; remove or migrate it manually."
    )


def _fallback_generated_sources_for_removed_entity(
    *,
    metadata: MetadataProject,
    entity_name: str,
) -> list[str]:
    root = Path("src") / "main" / "java" / package_path(base_package(metadata))
    files = {
        root / "domain" / f"{entity_name}.java",
        root / "repository" / f"{entity_name}Repository.java",
        root / "service" / f"{entity_name}ServiceBase.java",
        root / "adapter" / "inbound" / f"{entity_name}Controller.java",
        root / "adapter" / "inbound" / f"{entity_name}CreateRequest.java",
        root / "adapter" / "inbound" / f"{entity_name}UpdateRequest.java",
        root / "adapter" / "inbound" / f"{entity_name}Response.java",
        root / "adapter" / "outbound" / f"{entity_name}StagingWriter.java",
        root / "batch" / f"{entity_name}EodBatchJob.java",
    }
    return sorted(path.as_posix() for path in files)


def _warn_orphaned_developer_services(
    *,
    metadata: MetadataProject,
    output_dir: Path,
    removed_entities: set[str | None],
) -> list[str]:
    warnings: list[str] = []
    root = output_dir / "src" / "main" / "java" / package_path(base_package(metadata))
    service_dir = root / "service"
    for entity_name in sorted(name for name in removed_entities if name):
        developer_service = service_dir / f"{entity_name}Service.java"
        if not developer_service.exists() or not developer_service.is_file():
            continue
        if read_edgeforge_ownership(developer_service) == "developer":
            backup_path = _archive_orphaned_developer_file(developer_service)
            message = _orphaned_developer_warning(
                entity_name,
                output_dir,
                developer_service,
                backup_path,
            )
            if message not in warnings:
                warnings.append(message)
    return warnings
