"""Audit helpers for generated output files."""

from __future__ import annotations

from appbuilder.core import CURRENT_MANIFEST_SCHEMA_VERSION


def safe_source_manifest_label(source_manifest: str) -> str:
    """Return a generated-artifact-safe manifest label with no host path segments."""

    raw_value = str(source_manifest or "").strip()
    if not raw_value:
        return "metadata-project"
    normalized = raw_value.replace("\\", "/").rstrip("/")
    label = normalized.rsplit("/", 1)[-1] if normalized else ""
    return label or "manifest"


def render_generated_file_header(
    *,
    source_manifest: str,
    target_profile: str,
    generation_run_id: str,
    comment_style: str = "slash",
    ownership: str = "generated",
    manifest_schema_version: str = CURRENT_MANIFEST_SCHEMA_VERSION,
) -> str:
    """Return a standard generated-file header comment."""

    if ownership not in {"generated", "developer"}:
        raise ValueError(f"Unsupported EdgeForge ownership '{ownership}'")

    source_manifest_label = safe_source_manifest_label(source_manifest)

    if comment_style == "xml":
        return "\n".join(
            [
                "<!-- Generated by EdgeForge -->",
                f"<!-- EdgeForge-ownership: {ownership} -->",
                f"<!-- Source manifest: {source_manifest_label} -->",
                f"<!-- Manifest schema version: {manifest_schema_version} -->",
                f"<!-- Target profile: {target_profile} -->",
                f"<!-- Generation run: {generation_run_id} -->",
            ]
        )

    prefix = _resolve_comment_prefix(comment_style)
    return "\n".join(
        [
            f"{prefix} Generated by EdgeForge",
            f"{prefix} EdgeForge-ownership: {ownership}",
            f"{prefix} Source manifest: {source_manifest_label}",
            f"{prefix} Manifest schema version: {manifest_schema_version}",
            f"{prefix} Target profile: {target_profile}",
            f"{prefix} Generation run: {generation_run_id}",
        ]
    )


def _resolve_comment_prefix(comment_style: str) -> str:
    if comment_style == "slash":
        return "//"
    if comment_style == "sql":
        return "--"
    if comment_style == "hash":
        return "#"
    raise ValueError(f"Unsupported comment style '{comment_style}'")
