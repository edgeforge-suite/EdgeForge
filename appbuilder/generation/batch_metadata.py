BATCH_METADATA_SCHEMA_ID = "pkg-batch-metadata"
BATCH_METADATA_SCHEMA_CONTRACT_VERSION = 1
SPRING_BATCH_METADATA_SCHEMA_VERSION = "5.1.2"
PREVIEW_BATCH_METADATA_SCHEMA_VERSION = "6.0.5"

BATCH_METADATA_OBJECT_NAMES = frozenset(
    {
        "BATCH_JOB_EXECUTION",
        "BATCH_JOB_EXECUTION_CONTEXT",
        "BATCH_JOB_EXECUTION_PARAMS",
        "BATCH_JOB_EXECUTION_SEQ",
        "BATCH_JOB_INSTANCE",
        "BATCH_JOB_SEQ",
        "BATCH_JOB_INSTANCE_SEQ",
        "BATCH_STEP_EXECUTION",
        "BATCH_STEP_EXECUTION_CONTEXT",
        "BATCH_STEP_EXECUTION_SEQ",
    }
)

_CREATE_SCHEMA_OBJECT_PATTERN = re.compile(
    r"\bCREATE\s+(?:TABLE|SEQUENCE)\s+(?:IF\s+NOT\s+EXISTS\s+)?"
    r"(?:(?:[A-Za-z_][A-Za-z0-9_$]*|\"[A-Za-z_][A-Za-z0-9_$]*\")\s*\.\s*)?"
    r"(?:\"([A-Za-z_][A-Za-z0-9_$]*)\"|([A-Za-z_][A-Za-z0-9_$]*))",
    re.IGNORECASE,
)

