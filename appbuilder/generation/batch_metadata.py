def has_run_semantics(metadata: MetadataProject) -> bool:
    """Return whether this CRUD package has any validated opt-in handoff."""

    return any(contract.run_semantics is not None for contract in metadata.contracts)


def has_batch_jobs(metadata: MetadataProject, target_profile: TargetProfile) -> bool:
    """Use the Java artifact plan, not contract presence, to select Batch runtime."""

    from .java_emitter import (
        _entity_java_artifact_plan,
        _has_downstream_file_contract_for_entity,
        _has_handoffs_for_entity,
    )
    from .utils import all_entities

    return any(
        _entity_java_artifact_plan(
            metadata=metadata, entity=entity, target_profile=target_profile
        ).emit_batch_job
        for entity in all_entities(metadata)
        if entity.fields and (
            _has_handoffs_for_entity(metadata, entity.name)
            or _has_downstream_file_contract_for_entity(metadata, entity.name)
        )
    )


def owns_batch_metadata(metadata: MetadataProject, target_profile: TargetProfile) -> bool:
    """Keep legacy ownership unchanged; all preview jobs have one Flyway owner."""

    return has_run_semantics(metadata) or (
        target_profile.experimental_boot41 and has_batch_jobs(metadata, target_profile)
    )


def batch_metadata_schema_sql(target_profile: TargetProfile) -> str:
    """Return the pinned, profile-appropriate Flyway schema without upgrading history."""

    database = target_profile.runtime_database_dependency
    if database == "postgresql":
        sql = _POSTGRESQL_SCHEMA_SQL
    elif database == "h2":
        sql = _H2_SCHEMA_SQL
    else:
        raise ValueError(
            "Batch jobs require a supported metadata schema for target profile "
            f"'{target_profile.name}' (database '{database}')."
        )
    # Verified against both schemas in the 6.0.5 source artifact: the sole
    # executable change from these pinned 5.1.2 schemas is this sequence name.
    if target_profile.experimental_boot41:
        return sql.replace("BATCH_JOB_SEQ", "BATCH_JOB_INSTANCE_SEQ")
    return sql


def batch_metadata_internal_schema(target_profile: TargetProfile) -> dict[str, Any]:
    """Return the deterministic package-singleton baseline entry."""

    sql_statements = normalized_batch_metadata_sql_statements(target_profile)
    schema_version = (
        PREVIEW_BATCH_METADATA_SCHEMA_VERSION
        if target_profile.experimental_boot41
        else SPRING_BATCH_METADATA_SCHEMA_VERSION
    )
    payload = {
        "schema_contract_version": BATCH_METADATA_SCHEMA_CONTRACT_VERSION,
        "target_profile": target_profile.name,
        "spring_batch_metadata_schema_version": schema_version,
        "sql_statements": sql_statements,
    }
    return {
        "id": BATCH_METADATA_SCHEMA_ID,
        "schema_contract_version": BATCH_METADATA_SCHEMA_CONTRACT_VERSION,
        "target_profile": target_profile.name,
        "spring_batch_metadata_schema_version": schema_version,
        "content_sha256": hashlib.sha256(
            json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
        ).hexdigest(),
    }


def normalized_batch_metadata_sql_statements(target_profile: TargetProfile) -> list[str]:
    """Normalize SQL for fingerprinting while preserving statement execution order."""

    return [
        re.sub(r"\s+", " ", statement).strip()
        for statement in batch_metadata_schema_sql(target_profile).split(";")
        if statement.strip()
    ]


def reserved_batch_metadata_objects_in_sql(sql: str) -> list[str]:
    """Return reserved Batch objects directly created by executable SQL text."""

    executable_sql = _mask_sql_comments_and_string_literals(sql)
    objects = {
        (match.group(1) or match.group(2)).upper()
        for match in _CREATE_SCHEMA_OBJECT_PATTERN.finditer(executable_sql)
    }
    return sorted(objects & BATCH_METADATA_OBJECT_NAMES)


def _mask_sql_comments_and_string_literals(sql: str) -> str:
    """Mask non-executable SQL regions while preserving token boundaries."""

    masked = list(sql)
    index = 0
    while index < len(sql):
        if sql.startswith("--", index):
            end = sql.find("\n", index + 2)
            end = len(sql) if end < 0 else end
            for position in range(index, end):
                masked[position] = " "
            index = end
            continue
        if sql.startswith("/*", index):
            end = sql.find("*/", index + 2)
            end = len(sql) if end < 0 else end + 2
            for position in range(index, end):
                if masked[position] not in "\r\n":
                    masked[position] = " "
            index = end
            continue
        if sql[index] == "'":
            end = index + 1
            while end < len(sql):
                if sql[end] == "\\" and end + 1 < len(sql):
                    end += 2
                    continue
                if sql[end] == "'":
                    if end + 1 < len(sql) and sql[end + 1] == "'":
                        end += 2
                        continue
                    end += 1
                    break
                end += 1
            for position in range(index, end):
                if masked[position] not in "\r\n":
                    masked[position] = " "
            index = end
            continue
        if sql[index] == "$":
            delimiter = re.match(r"\$(?:[A-Za-z_][A-Za-z0-9_]*)?\$", sql[index:])
            if delimiter is not None:
                token = delimiter.group(0)
                end = sql.find(token, index + len(token))
                end = len(sql) if end < 0 else end + len(token)
                for position in range(index, end):
                    if masked[position] not in "\r\n":
                        masked[position] = " "
                index = end
                continue
        index += 1
    return "".join(masked)
